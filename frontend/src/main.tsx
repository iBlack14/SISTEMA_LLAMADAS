import { lazy,StrictMode,Suspense } from "react";
import { createRoot } from "react-dom/client";
import "./styles.css";
import "./modules.css";
import "./controls.css";
const Dashboard=lazy(()=>import("./Dashboard").then(module=>({default:module.Dashboard})));
const Contacts=lazy(()=>import("./App").then(module=>({default:module.App})));
const Reports=lazy(()=>import("./Reports").then(module=>({default:module.Reports})));
const Network=lazy(()=>import("./Network").then(module=>({default:module.Network})));
const Login=lazy(()=>import("./Login").then(module=>({default:module.Login})));
const path=location.pathname;
const Page=path==="/login"?Login:path.startsWith("/admin/nucleo-red")?Network:path.startsWith("/panel/reports")?Reports:path.startsWith("/panel/contacts")?Contacts:Dashboard;
createRoot(document.getElementById("root")!).render(<StrictMode><Suspense fallback={<p className="app-loading" role="status">Cargando la vista…</p>}><Page/></Suspense></StrictMode>);
